  function routeFromLabel(text) {
    var clean = String(text || '').replace(/\s+/g, ' ').trim();
    if (ENGLISH_LABELS.test(clean)) return 'en';
    if (SPANISH_LABELS.test(clean)) return 'es';
    return '';
  }
  function isEnglish() {
    try {
      var selected = localStorage.getItem(KEY);
      if (selected === 'en' || selected === 'es') return selected === 'en';
      if (window.Lang && /^en/i.test(String(window.Lang.current || window.Lang.lang || ''))) return true;
      if (document.documentElement.lang === 'en') return true;
    } catch (e) {}
    return false;
  }
  function rememberRoute(event) {
    var node = event.target && event.target.closest ? event.target.closest('button,a,[role="button"],label,[tabindex]') : null;
    if (!node) return;
    var text = (node.innerText || node.textContent || '') + ' ' + (node.getAttribute('aria-label') || '');
    var lang = routeFromLabel(text);
    if (!lang) return;
    try { localStorage.setItem(KEY, lang); } catch (e) {}
    // Keep document language metadata aligned with the selected learning route.
    try { document.documentElement.lang = lang; } catch (e) {}
    // Set the app's existing language manager before the route click handler renders its screen.
    try {
      if (window.Lang && typeof window.Lang === 'object') {
        window.Lang.current = lang;
        if (typeof window.Lang.setLanguage === 'function') window.Lang.setLanguage(lang);
        else if (typeof window.Lang.set === 'function') window.Lang.set(lang);
      }
    } catch (e) {}
    setTimeout(run, 0);
  }
